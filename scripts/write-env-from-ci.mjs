/* write-env-from-ci.mjs
 *
 * Writes src/environments/environment.local.ts from environment variables, for
 * the GitHub Actions build (see .github/workflows/deploy-pages.yml). The file
 * itself is gitignored, because its values are per-project rather than because
 * they are secret — a Firebase web config is public by design, and firestore.rules
 * is what actually protects the data.
 *
 * Fails loudly if a required value is missing: a build that silently ships
 * placeholder config produces a site that looks fine and cannot load anything.
 */

import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REQUIRED = [
  'FIREBASE_API_KEY',
  'FIREBASE_AUTH_DOMAIN',
  'FIREBASE_PROJECT_ID',
  'FIREBASE_STORAGE_BUCKET',
  'FIREBASE_MESSAGING_SENDER_ID',
  'FIREBASE_APP_ID',
];

const missing = REQUIRED.filter((name) => !process.env[name]);
if (missing.length > 0) {
  console.error(
    `Missing repository variable(s): ${missing.join(', ')}.\n` +
      'Set them under Settings > Secrets and variables > Actions > Variables. See SETUP.md.',
  );
  process.exit(1);
}

const config = {
  apiKey: process.env.FIREBASE_API_KEY,
  authDomain: process.env.FIREBASE_AUTH_DOMAIN,
  projectId: process.env.FIREBASE_PROJECT_ID,
  storageBucket: process.env.FIREBASE_STORAGE_BUCKET,
  messagingSenderId: process.env.FIREBASE_MESSAGING_SENDER_ID,
  appId: process.env.FIREBASE_APP_ID,
  ...(process.env.FIREBASE_MEASUREMENT_ID
    ? { measurementId: process.env.FIREBASE_MEASUREMENT_ID }
    : {}),
};

const contents = `// Generated by scripts/write-env-from-ci.mjs during the GitHub Pages build.
// Do not edit; do not commit.
import { AppEnvironment } from './environment.types';

export const environment: AppEnvironment = {
  production: true,
  useEmulator: false,
  firebase: ${JSON.stringify(config, null, 2).replace(/\n/g, '\n  ')},
  adminEmail: ${JSON.stringify(process.env.ADMIN_EMAIL ?? '')},
};
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  '../src/environments/environment.local.ts',
);
writeFileSync(target, contents);
console.log(`Wrote ${target} for project ${config.projectId}.`);
